import React, { useState, useEffect } from 'react';
import { optimizationService } from '../services/api';
import { useAuth } from '../context/AuthContext';
import { useToast } from '../context/ToastContext';
import StatusBadge from '../components/common/StatusBadge';
import LoadingSpinner from '../components/common/LoadingSpinner';
import {
  FileCheck2,
  Building2,
  Package,
  Boxes,
  Clock,
  ShoppingCart,
  CheckCircle2,
  Sparkles,
  ArrowRight
} from 'lucide-react';

const Recommendations = () => {
  const [recommendations, setRecommendations] = useState([]);
  const [loading, setLoading] = useState(true);
  const [statusFilter, setStatusFilter] = useState('All');
  const [updatingId, setUpdatingId] = useState(null);

  const { isAdmin } = useAuth();
  const { showToast } = useToast();

  const fetchRecommendations = async () => {
    try {
      setLoading(true);
      const res = await optimizationService.getRecommendations({ status: statusFilter });
      setRecommendations(res.data);
    } catch (err) {
      console.error(err);
      showToast('Failed to fetch purchase recommendations', 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchRecommendations();
  }, [statusFilter]);

  const handleStatusChange = async (id, newStatus) => {
    try {
      setUpdatingId(id);
      await optimizationService.updateRecommendationStatus(id, newStatus);
      if (newStatus === 'Completed') {
        showToast('Purchase Order marked COMPLETED & Stock Restocked!', 'success');
      } else {
        showToast(`Status updated to "${newStatus}"`, 'info');
      }
      fetchRecommendations();
    } catch (err) {
      showToast(err.response?.data?.message || 'Failed to update status', 'error');
    } finally {
      setUpdatingId(null);
    }
  };

  return (
    <div className="space-y-6">
      {/* Title */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl font-bold text-white tracking-tight flex items-center gap-2">
            <FileCheck2 className="w-6 h-6 text-indigo-400" />
            Purchase Order Recommendations
          </h1>
          <p className="text-xs text-slate-400">
            Supplier reorder recommendations generated by the optimization engine.
          </p>
        </div>

        {/* Filter Buttons */}
        <div className="flex items-center gap-2">
          {['All', 'Pending', 'Ordered', 'Completed'].map((filter) => (
            <button
              key={filter}
              onClick={() => setStatusFilter(filter)}
              className={`px-3.5 py-1.5 rounded-xl text-xs font-semibold border transition-all ${
                statusFilter === filter
                  ? 'bg-indigo-600 text-white border-indigo-500 shadow-md shadow-indigo-600/20'
                  : 'bg-slate-900 text-slate-400 border-slate-800 hover:text-slate-200'
              }`}
            >
              {filter}
            </button>
          ))}
        </div>
      </div>

      {loading ? (
        <LoadingSpinner label="Fetching purchase order recommendations..." />
      ) : recommendations.length === 0 ? (
        <div className="py-16 text-center bg-slate-900 border border-slate-800 rounded-2xl space-y-3">
          <FileCheck2 className="w-12 h-12 text-slate-600 mx-auto" />
          <h3 className="text-base font-semibold text-slate-300">No recommendations found</h3>
          <p className="text-xs text-slate-500 max-w-sm mx-auto">
            Use the "Create Purchase Recommendation" button on the Optimization page to generate reorder specs for low stock items.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
          {recommendations.map((rec) => {
            const isUpdating = updatingId === rec._id;

            return (
              <div
                key={rec._id}
                className="p-6 rounded-2xl bg-slate-900 border border-slate-800 hover:border-slate-700 transition-all flex flex-col justify-between space-y-4 shadow-xl"
              >
                <div className="space-y-3">
                  <div className="flex items-start justify-between">
                    <div>
                      <h3 className="font-extrabold text-white text-base">
                        {rec.product?.name || 'Unknown Product'}
                      </h3>
                      <p className="text-xs font-mono text-indigo-300">
                        SKU: {rec.product?.SKU || 'N/A'}
                      </p>
                    </div>
                    <StatusBadge status={rec.status} />
                  </div>

                  {/* Supplier Card */}
                  <div className="p-3 rounded-xl bg-slate-950 border border-slate-800 text-xs space-y-1">
                    <div className="flex items-center gap-1.5 font-semibold text-slate-200">
                      <Building2 className="w-3.5 h-3.5 text-indigo-400" />
                      <span>Supplier: {rec.supplier?.companyName || 'Unassigned'}</span>
                    </div>
                    <p className="text-[11px] text-slate-400 pl-5">
                      Contact: {rec.supplier?.name} ({rec.supplier?.phone || 'No phone'})
                    </p>
                  </div>

                  {/* Quantities Overview */}
                  <div className="grid grid-cols-2 gap-3 p-3 rounded-xl bg-slate-950/60 border border-slate-800/80 text-center">
                    <div>
                      <span className="text-[10px] text-slate-500 uppercase block font-semibold">Current Stock</span>
                      <span className="text-sm font-extrabold text-rose-400">{rec.currentStock} units</span>
                    </div>
                    <div>
                      <span className="text-[10px] text-slate-500 uppercase block font-semibold">Recommended Order</span>
                      <span className="text-sm font-extrabold text-emerald-400">{rec.recommendedQuantity} units</span>
                    </div>
                  </div>
                </div>

                {/* Status Action Pipeline Controls (Admin Only) */}
                {isAdmin && (
                  <div className="pt-3 border-t border-slate-800 space-y-2">
                    <span className="text-[10px] font-semibold text-slate-400 uppercase tracking-wider block">
                      Update Order Status:
                    </span>
                    <div className="grid grid-cols-3 gap-1.5">
                      <button
                        type="button"
                        disabled={isUpdating || rec.status === 'Pending'}
                        onClick={() => handleStatusChange(rec._id, 'Pending')}
                        className={`py-1.5 px-2 rounded-lg text-[11px] font-semibold transition-all ${
                          rec.status === 'Pending'
                            ? 'bg-amber-500/20 text-amber-400 border border-amber-500/40'
                            : 'bg-slate-950 text-slate-400 border border-slate-800 hover:bg-slate-800'
                        }`}
                      >
                        Pending
                      </button>

                      <button
                        type="button"
                        disabled={isUpdating || rec.status === 'Ordered'}
                        onClick={() => handleStatusChange(rec._id, 'Ordered')}
                        className={`py-1.5 px-2 rounded-lg text-[11px] font-semibold transition-all ${
                          rec.status === 'Ordered'
                            ? 'bg-sky-500/20 text-sky-400 border border-sky-500/40'
                            : 'bg-slate-950 text-slate-400 border border-slate-800 hover:bg-slate-800'
                        }`}
                      >
                        Ordered
                      </button>

                      <button
                        type="button"
                        disabled={isUpdating || rec.status === 'Completed'}
                        onClick={() => handleStatusChange(rec._id, 'Completed')}
                        className={`py-1.5 px-2 rounded-lg text-[11px] font-semibold transition-all ${
                          rec.status === 'Completed'
                            ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/40'
                            : 'bg-slate-950 text-slate-400 border border-slate-800 hover:bg-slate-800'
                        }`}
                      >
                        Completed
                      </button>
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};

export default Recommendations;
